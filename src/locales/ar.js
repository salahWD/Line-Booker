/**
 * Looks up "a.b.c" in the messages and replaces {placeholders}.
 * Returns the key itself when missing, so gaps are easy to spot in the UI.
 */
export function t(key, vars) {
  const value = key.split('.').reduce((obj, part) => (obj == null ? obj : obj[part]), ar);
  if (typeof value !== 'string') return value ?? key;
  if (!vars) return value;
  return value.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? `{${name}}`));
}
